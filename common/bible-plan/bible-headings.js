// 诗歌体/引文特殊缩进章节规则（整段引述旧约诗歌体排版）
export const POETRY_VERSES = {
	'40_2_6': true,
	'40_2_18': true
};

export function getSectionHeading(volumeSN, chapter, verse) {
	const key = `${Number(volumeSN)}_${Number(chapter)}`;
	const verseNum = Number(verse);
	if (SECTION_HEADINGS[key] && SECTION_HEADINGS[key][verseNum]) {
		return SECTION_HEADINGS[key][verseNum];
	}
	return null;
}

export function isPoetryVerse(volumeSN, chapter, verse) {
	const key = `${volumeSN}_${chapter}_${verse}`;
	if (POETRY_VERSES[key]) return true;
	if ([19, 20, 22, 25].includes(Number(volumeSN))) {
		return true;
	}
	return false;
}

export function parseProperNouns(text) {
	if (!text) return [];
	// 正则匹配所有专有名词，保证最长优先匹配
	const sortedNouns = [...PROPER_NOUNS].sort((a, b) => b.length - a.length);
	const regex = new RegExp(`(${sortedNouns.join('|')})`, 'g');
	const parts = text.split(regex);
	return parts.filter(p => p.length > 0).map(part => ({
		text: part,
		isNoun: PROPER_NOUNS.includes(part)
	}));
}
